package corejava.part1.basicConcepts;

public class EscapeSequence {

    static void main(String[] args) {
        System.out.println("HELLO \nSam");
        System.out.println("HELLO \tSam");
        System.out.println("HELLO \bSam");
        System.out.println("\\");
        System.out.println("'" + " AND " + "\'");
        System.out.println("\"");
    }
}
